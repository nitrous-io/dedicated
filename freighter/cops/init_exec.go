package cops

import (
	"encoding/json"
	"flag"
	"fmt"
	"io"
	"log"
	"os"
	"runtime"
	"strconv"
	"sync"
	"syscall"

	"github.com/nitrous-io/dedicated/pkg/reexec"
)

const execCommandName = "cops-exec"

func init() {
	reexec.Register(execCommandName, execInit)
}

// execInit runs inside the container mnt namespace, and process websocket messages
func execInit() {
	runtime.LockOSThread()
	flag.Parse()
	id := flag.Arg(0)

	if err := syscall.Chdir("/"); err != nil {
		log.Fatalf("execInit failed to change dir to / : %v", err)
	}

	// this is used to communicate with the parent process
	pipe := os.NewFile(3, "pipe")
	defer pipe.Close()
	errCh := ListenAndServe(id, os.Stdin, pipe)
	if err := <-errCh; err != nil {
		log.Fatalf("failed to serve cops websocket %v", err)
	}
	os.Exit(0)
}

func fileWatcher(mu *sync.Mutex, encoder *json.Encoder) {
	watcher, err := NewRecursiveWatcher("/home/nitrous")
	if err != nil {
		log.Printf("NewRecursiveWather() failed with '%s'\n")
		return
	}
	watcher.Run()
	defer watcher.Close()
	for {
		select {
		case folder := <-watcher.Folders:
			log.Printf("cops folder '%s' changed\n", folder)
			args := []interface{}{folder}
			msg := &Message{
				Namespace: "watcher",
				Event:     "dirchanged",
				Args:      args,
			}
			mu.Lock()
			err := encoder.Encode(msg)
			mu.Unlock()
			// can happen when ws connetion is closed
			if err != nil {
				log.Printf("fileWatcher: encoder.Encode() failed with '%s'\n", err)
				return
			}
		}
	}
}

// this is run inside a chroot environment and processes the actual container
// request.
func ListenAndServe(id string, r io.Reader, w io.Writer) chan error {
	var mu sync.Mutex

	decoder := json.NewDecoder(r)
	encoder := json.NewEncoder(w)

	fsHandler := NewFsHandler(id)
	finderHandler := NewFinderHandler(id)

	errCh := make(chan error, 1)

	go fileWatcher(&mu, encoder)

	go func() {
		for {
			msg := &Message{}
			if err := decoder.Decode(msg); err != nil {
				errCh <- fmt.Errorf("failed to decode msg %s", err)
				return
			}

			var handlerToRun *AsyncHandler

			log.Printf("cops cmd: '%s.%s'\n", msg.Namespace, msg.Event)
			switch msg.Namespace {
			case "fs":
				handlerToRun = &fsHandler
			case "finder":
				handlerToRun = &finderHandler
			default:
				errCh <- fmt.Errorf("invalid operation %s", msg.Namespace)
				return
			}

			// handle the operation in a separate goroutine to not block the
			// message pipeline
			go func(h AsyncHandler) {
				ch := h.HandleAsync(msg)
				for reply := range ch {
					mu.Lock()
					err := encoder.Encode(reply)
					mu.Unlock()
					if err != nil {
						errCh <- fmt.Errorf("failed to encode %v, %s", reply, err)
						return
					}
				}
			}(*handlerToRun)
		}
	}()
	return errCh
}

// Start listening to messages meant for container with `id`, spins up a
// chroot-d process for that container and proxy data in/out of the chrooted
// process.
// This is run in the parent process
func Start(id string, r io.Reader, w io.Writer) (done chan error, quit chan error, err error) {
	initPID, err := GetContainerPID(id)
	if err != nil {
		return nil, nil, fmt.Errorf("failed to get container %s pid: %v", id, err)
	}

	parent, child, err := os.Pipe()
	if err != nil {
		return nil, nil, err
	}

	// create the command, pass the child as fd3 of the command
	cmd := reexec.Command(execCommandName, strconv.Itoa(initPID))
	stdin, err := cmd.StdinPipe()
	if err != nil {
		return nil, nil, err
	}
	cmd.ExtraFiles = []*os.File{child}
	// pipe the output/errors to os stdout/stderr
	cmd.Stdout = os.Stdout
	cmd.Stderr = os.Stderr

	// parent doesnt need the child, so close it asap
	if err := cmd.Start(); err != nil {
		child.Close()
		return nil, nil, err
	}
	child.Close()

	// copy data in and out of the child process
	// input goes to stdin
	// output comes from the pipe, not stdout because stdout/stderr may
	// contains logs generated by the child process
	quit = make(chan error, 2)
	go func() {
		_, err := io.Copy(w, parent)
		quit <- err
	}()
	go func() {
		_, err := io.Copy(stdin, r)
		quit <- err
	}()
	// listen to quit and kill the commmand whenever the pipes are closed
	go func() {
		<-quit
		if cmd.Process != nil {
			cmd.Process.Kill()
		}
	}()
	done = make(chan error)
	// write to error channel whenever the command finishes
	go func() {
		done <- cmd.Wait()
		close(done)
	}()
	return done, quit, nil
}
