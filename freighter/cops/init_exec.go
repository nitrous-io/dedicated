package cops

import (
	"encoding/json"
	"flag"
	"fmt"
	"io"
	"log"
	"os"
	"runtime"
	"strconv"
	"sync"
	"syscall"

	"github.com/nitrous-io/dedicated/pkg/reexec"
)

const execCommandName = "cops-exec"

func init() {
	reexec.Register(execCommandName, execInit)
}

// execInit runs inside the container mnt namespace, and process websocket messages
func execInit() {
	runtime.LockOSThread()
	flag.Parse()
	id := flag.Arg(0)

	if err := syscall.Chdir("/"); err != nil {
		log.Fatalf("execInit failed to change dir to / : %v", err)
	}

	// this is used to communicate with the parent process
	pipe := os.NewFile(3, "pipe")
	defer pipe.Close()
	opsHandler := NewOpsHandler(id, os.Stdin, pipe)
	err := opsHandler.StartAndWaitFinished()
	if err != nil {
		log.Fatalf("opsHandler.StartAndWaitFinished() failed with %v", err)
	}
	os.Exit(0)
}

type OpsHandler struct {
	containerId string
	r           io.Reader
	w           io.Writer
	mu          sync.Mutex
	errCh       chan error
	decoder     *json.Decoder
	encoder     *json.Encoder
}

func NewOpsHandler(id string, r io.Reader, w io.Writer) *OpsHandler {
	return &OpsHandler{
		containerId: id,
		r:           r,
		w:           w,
	}
}

func (oh *OpsHandler) StartAndWaitFinished() error {
	oh.decoder = json.NewDecoder(oh.r)
	oh.encoder = json.NewEncoder(oh.w)
	oh.errCh = make(chan error, 1)
	go oh.fileWatcher()
	go oh.mainLoop()
	return oh.waitFinished()
}

func (oh *OpsHandler) waitFinished() error {
	err := <-oh.errCh
	return err
}

func (oh *OpsHandler) sendReply(msg *Message) error {
	oh.mu.Lock()
	err := oh.encoder.Encode(msg)
	oh.mu.Unlock()
	if err != nil {
		err = fmt.Errorf("failed to encode %v, %s", msg, err)
	}
	return err
}

func (oh *OpsHandler) fileWatcher() {
	watcher, err := NewRecursiveWatcher("/home/nitrous")
	if err != nil {
		log.Printf("NewRecursiveWather() failed with '%s'\n", err)
		return
	}
	watcher.Run()
	defer watcher.Close()
	for {
		select {
		case dir := <-watcher.Folders:
			log.Printf("cops watcher dir '%s' changed\n", dir)
			msg := &Message{
				Namespace: "watcher",
				Event:     "dir_changed.output",
			}
			msg.Args = []interface{}{dir}
			oh.sendReply(msg)
			// can happen when ws connetion is closed
			if err != nil {
				log.Printf("oh.sendReply() failed with '%s'\n", err)
				oh.errCh <- err
				return
			}
		}
	}
}

func (oh *OpsHandler) runHandler(h AsyncHandler, msg *Message) {
	ch := h.HandleAsync(msg)
	for reply := range ch {
		err := oh.sendReply(reply)
		if err != nil {
			oh.errCh <- fmt.Errorf("oh.sendReply() failed with '%s'", err)
		}
	}
}

// handle the operation in a separate goroutine to not block the
// message pipeline
func (oh *OpsHandler) runHandlerAsync(h AsyncHandler, msg *Message) {
	go oh.runHandler(h, msg)
}

// this is run inside a chroot environment and processes the actual container
// request.
func (oh *OpsHandler) mainLoop() {
	// cache handlers
	fsHandler := NewFsHandler(oh.containerId)
	finderHandler := NewFinderHandler(oh.containerId)

	for {
		msg := &Message{}
		err := oh.decoder.Decode(msg)
		if err != nil {
			oh.errCh <- fmt.Errorf("failed to decode msg %s", err)
			return
		}

		log.Printf("cops cmd: '%s.%s'\n", msg.Namespace, msg.Event)
		switch msg.Namespace {
		case "fs":
			oh.runHandlerAsync(fsHandler, msg)
		case "finder":
			oh.runHandlerAsync(finderHandler, msg)
		default:
			oh.errCh <- fmt.Errorf("invalid operation %s", msg.Namespace)
			return
		}
	}
}

// Start listening to messages meant for container with `id`, spins up a
// chroot-d process for that container and proxy data in/out of the chrooted
// process.
// This is run in the parent process
func Start(id string, r io.Reader, w io.Writer) (done chan error, quit chan error, err error) {
	initPID, err := GetContainerPID(id)
	if err != nil {
		return nil, nil, fmt.Errorf("failed to get container %s pid: %v", id, err)
	}

	parent, child, err := os.Pipe()
	if err != nil {
		return nil, nil, err
	}

	// create the command, pass the child as fd3 of the command
	cmd := reexec.Command(execCommandName, strconv.Itoa(initPID))
	stdin, err := cmd.StdinPipe()
	if err != nil {
		return nil, nil, err
	}
	cmd.ExtraFiles = []*os.File{child}
	// pipe the output/errors to os stdout/stderr
	cmd.Stdout = os.Stdout
	cmd.Stderr = os.Stderr

	// parent doesnt need the child, so close it asap
	if err := cmd.Start(); err != nil {
		child.Close()
		return nil, nil, err
	}
	child.Close()

	// copy data in and out of the child process
	// input goes to stdin
	// output comes from the pipe, not stdout because stdout/stderr may
	// contains logs generated by the child process
	quit = make(chan error, 2)
	go func() {
		_, err := io.Copy(w, parent)
		quit <- err
	}()
	go func() {
		_, err := io.Copy(stdin, r)
		quit <- err
	}()
	// listen to quit and kill the commmand whenever the pipes are closed
	go func() {
		<-quit
		if cmd.Process != nil {
			cmd.Process.Kill()
		}
	}()
	done = make(chan error)
	// write to error channel whenever the command finishes
	go func() {
		done <- cmd.Wait()
		close(done)
	}()
	return done, quit, nil
}
