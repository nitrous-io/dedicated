var _ = BeforeSuite(func() {
	var (
		start time.Time
		err   error
		out   []byte
		cmd   *exec.Cmd
	)

	// build base, which is busybox with /sh as CMD
	start = time.Now()
	fmt.Print("build base:latest...")
	cmd = exec.Command("docker", "build", "-t", "base:latest", ".")
	cmd.Dir = "/docker-busybox"
	out, err = cmd.CombinedOutput()
	Expect(err).To(BeNil(), "failed to build base, output: %s", string(out))
	fmt.Printf(" took %s\n", time.Now().Sub(start))

	// build busybox, which is busybox duh but with top as CMD
	start = time.Now()
	fmt.Print("build busybox:latest...")
	cmd = exec.Command("docker", "build", "-t", "busybox:latest", "-")
	cmd.Stdin = bytes.NewBufferString(`
	FROM base:latest
	CMD ["top"]
	`)
	out, err = cmd.CombinedOutput()
	Expect(err).To(BeNil(), "failed to build busybox, output: %s", string(out))
	fmt.Printf(" took %s\n", time.Now().Sub(start))

	// build busybox-volumes which has two built-in volumes
	start = time.Now()
	fmt.Print("build busybox-volumes:latest...")
	cmd = exec.Command("docker", "build", "-t", "busybox-volumes:latest", "-")
	cmd.Stdin = bytes.NewBufferString(`
	FROM base:latest
	CMD ["top"]
	VOLUME /var/lib/docker
	VOLUME /var/lib/extra
	`)
	out, err = cmd.CombinedOutput()
	Expect(err).To(BeNil(), "failed to build busybox-volumes, output: %s", string(out))
	fmt.Printf(" took %s\n", time.Now().Sub(start))

	// Load the stored ubuntu-bare image as nitrousio/ubuntu-bare so we don't,
	// have to pull it from the Internet.
	start = time.Now()
	fmt.Print("building nitrousio/ubuntu-bare:latest...")
	out, err = exec.Command("docker", "load", "-i", "/root/ubuntu-bare.tar.gz").CombinedOutput()
	Expect(err).To(BeNil(), "failed to load nitrousio/ubuntu-bare, output: %s", string(out))
	fmt.Printf(" took %s\n", time.Now().Sub(start))
})

// startContainer behaves similarly to startContainerWithData except that it
// pre-creates a tmpdir for you
func startContainer(image, config string) (*docker.DockerProvider, *provider.ContainerInfo, func(), error) {
	datadir, err := ioutil.TempDir("", "freightertest")
	if err != nil {
		return nil, nil, func() {}, err
	}
	return startContainerWithData(image, datadir, config)
}

// startContainerWithData returns a running container based on busybox:latest
// with random name, and the provider used to run the container
func startContainerWithData(image, datadir, config string) (*docker.DockerProvider, *provider.ContainerInfo, func(), error) {
	prov, err := docker.NewDockerProvider(datadir)
	if err != nil {
		return nil, nil, func() {
			os.RemoveAll(datadir)
		}, err
	}
	name := test.RandomName("freightertest")
	info, err := prov.CreateStart(name, image, "secret", config)
	if err != nil {
		return nil, nil, func() {
			os.RemoveAll(datadir)
		}, err
	}

	return prov, info, func() {
		os.RemoveAll(datadir)
		test.CleanUpContainer(name)
	}, nil
}

// remove backup images generated by reconfig
func removeBackupImages(prov *docker.DockerProvider) error {
	imageList, err := prov.ListImages()
	if err != nil {
		return err
	}
	toRemove := []string{}
	for _, img := range imageList {
		parts := strings.Split(img.Name, "-")
		if len(parts) >= 3 && parts[len(parts)-2] == "backup" && len(parts[len(parts)-1]) == 19 { // 19 == length of UnixNano
			toRemove = append(toRemove, img.Name)
		}
	}
	if len(toRemove) > 0 {
		test.RemoveImages(toRemove)
	}
	return nil
}

// inspect a field of the container/image in string format
func inspectField(name, field string) (string, error) {
	format := fmt.Sprintf("{{.%s}}", field)
	inspectCmd := exec.Command("docker", "inspect", "-f", format, name)
	b, err := inspectCmd.CombinedOutput()
	out := string(b)
	if err != nil {
		return "", fmt.Errorf("failed to inspect %s: %s", name, out)
	}
	return strings.TrimSpace(out), nil
}

// inspect a field of the container/image
func inspectFieldJSON(name, field string) (string, error) {
	format := fmt.Sprintf("{{json .%s}}", field)
	inspectCmd := exec.Command("docker", "inspect", "-f", format, name)
	b, err := inspectCmd.CombinedOutput()
	out := string(b)
	if err != nil {
		return "", fmt.Errorf("failed to inspect %s: %s", name, out)
	}
	return strings.TrimSpace(out), nil
}

// check if the env of container/image contains all expected env values
func assertEnv(name string, expected []string, unexpected []string) {
	envstr, err := inspectFieldJSON(name, "Config.Env")
	Expect(err).To(BeNil())

	var env []string
	err = json.Unmarshal([]byte(envstr), &env)
	Expect(err).To(BeNil())
	for _, v := range expected {
		Expect(env).To(ContainElement(v))
	}
	for _, v := range unexpected {
		Expect(env).NotTo(ContainElement(v))
	}
}

// assert if the container when running exposed the ports specified in expected PortMap
func assertPort(name string, expected []interface{}) {
	portCmd := exec.Command("docker", "port", name)
	b, err := portCmd.CombinedOutput()
	out := string(b)
	Expect(err).To(BeNil(), "failed to get ports of %s, output: %s", name, out)

	ports := strings.Split(strings.Trim(out, "\n "), "\n")
	Expect(ports).To(ConsistOf(expected...), "invalid ports %s", name)

	// assert that exposed ports also contains the ports in test
	exposedStr, err := inspectFieldJSON(name, "Config.ExposedPorts")
	Expect(err).To(BeNil())
	var exposedPorts map[string]struct{}
	err = json.Unmarshal([]byte(exposedStr), &exposedPorts)
	Expect(err).To(BeNil())

	// assert exposed ports
	for _, e := range expected {
		parts := strings.Split(e.(string), "->")
		port := strings.TrimSpace(parts[0])
		Expect(exposedPorts).To(HaveKey(port))
	}
}

// assert if the container contains the expected volumes
func assertVolumes(name string, expected map[string]string, unexpected []string) {
	isDockerPre18, err := isDockerPre18()
	Expect(err).To(BeNil())
	var volumes map[string]string

	if isDockerPre18 {
		vstr, err := inspectFieldJSON(name, "Volumes")
		Expect(err).To(BeNil())

		err = json.Unmarshal([]byte(vstr), &volumes)
		Expect(err).To(BeNil())
	} else {
		mountsJson, err := inspectFieldJSON(name, "Mounts")
		Expect(err).To(BeNil())
		var mounts []dockerclient.Mount
		volumes = make(map[string]string)

		err = json.Unmarshal([]byte(mountsJson), &mounts)
		Expect(err).To(BeNil())

		for _, mount := range mounts {
			volumes[mount.Destination] = mount.Source
		}
	}

	for k, v := range expected {
		Expect(volumes).To(HaveKeyWithValue(k, v))
	}
	for _, k := range unexpected {
		Expect(volumes).NotTo(HaveKey(k))
	}
}

// docker version
func getDockerVersion() (int, int, error) {
	dockerVersionCmd := exec.Command("docker", "-v")
	b, err := dockerVersionCmd.CombinedOutput()
	version := string(b)
	if err != nil {
		return 0, 0, fmt.Errorf("failed to get version: %s", version)
	}
	re, _ := regexp.Compile("Docker version (\\d+)\\.(\\d+).\\d+-nitrous")
	matches := re.FindStringSubmatch(version)
	if len(matches) == 3 {
		majorVersion, err := strconv.Atoi(matches[1])
		if err != nil {
			return 0, 0, fmt.Errorf("failed to get docker version: %+v: %+v", matches, err)
		}

		minorVersion, err := strconv.Atoi(matches[2])
		if err != nil {
			return 0, 0, fmt.Errorf("failed to get docker version %+v: %+v", matches, err)
		}
		return majorVersion, minorVersion, nil
	}
	return 0, 0, fmt.Errorf("invalid docker version format: %s", version)
}

func isDockerPre18() (bool, error) {
	major, minor, err := getDockerVersion()
	if err != nil {
		return false, err
	}

	if major > 1 || (major == 1 && minor >= 8) {
		return false, nil
	}

	return true, nil
}
